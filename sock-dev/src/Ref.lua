-- SockDev.Ref: shared helpers for Studio. Has no LocalPlayer dependency, so it
-- works on the server, on the client, and in Edit mode via execute_luau.
-- Edit mode:  local R = require(game.ServerStorage.SockDev.Ref:Clone())
-- (:Clone() avoids a stale require cache after reinstalling)
-- Source tools (grep/lines/patch/push/upsertStation) need Edit mode (plugin security).

local Ref = {}

local SES = nil
local function ses()
	if not SES then
		SES = game:GetService("ScriptEditorService")
	end
	return SES
end

-- "World2.Gate.Prompt" -> Instance. The first segment is tried as a Workspace child, then as a service.
function Ref.find(path)
	if typeof(path) == "Instance" then
		return path
	end
	if type(path) ~= "string" then
		return nil
	end
	local node = nil
	for seg in string.gmatch(path, "[^%.]+") do
		if node == nil then
			if seg == "Workspace" or seg == "workspace" then
				node = workspace
			else
				node = workspace:FindFirstChild(seg)
				if not node then
					local ok, svc = pcall(game.GetService, game, seg)
					node = (ok and svc) or game:FindFirstChild(seg)
				end
			end
		else
			node = node:FindFirstChild(seg)
		end
		if not node then
			return nil
		end
	end
	return node
end

function Ref.path(inst)
	local n = inst:GetFullName()
	return (string.gsub(n, "^Workspace%.", ""))
end

function Ref.worldPos(x)
	if typeof(x) ~= "Instance" then
		return nil
	end
	if x:IsA("ProximityPrompt") then
		return Ref.worldPos(x.Parent)
	end
	if x:IsA("BillboardGui") then
		return Ref.worldPos(x.Adornee or x.Parent)
	end
	if x:IsA("BasePart") then
		return x.Position
	end
	if x:IsA("Attachment") then
		return x.WorldPosition
	end
	if x:IsA("Model") then
		return x:GetPivot().Position
	end
	return nil
end

function Ref.prompts(root)
	local list = {}
	for _, d in (root or workspace):GetDescendants() do
		if d:IsA("ProximityPrompt") then
			table.insert(list, d)
		end
	end
	return list
end

local function v3(p)
	if not p then
		return "?"
	end
	return string.format("%.0f,%.0f,%.0f", p.X, p.Y, p.Z)
end
Ref.v3 = v3

-- Markdown reference of the place: stations, worlds, prompts, remotes, script modules.
-- Save the result as C:\Users\trist\Downloads\Claude\sock-reference.md
function Ref.dump(opts)
	opts = opts or {}
	local L = {}
	local function w(s)
		table.insert(L, s)
	end
	w("# Find THE Sock: generated reference")
	w("_Generated by SockDev.Ref.dump(). Regenerate this file instead of editing it by hand._")
	w("")

	local SS = game:GetService("ServerStorage")
	local RS = game:GetService("ReplicatedStorage")
	local stMod = (SS:FindFirstChild("SockDev") and SS.SockDev:FindFirstChild("Stations"))
		or (RS:FindFirstChild("SockDevRuntime") and RS.SockDevRuntime:FindFirstChild("Stations"))
	if stMod then
		local ok, st = pcall(require, stMod:Clone())
		if ok and type(st) == "table" then
			w("## Stations (SockDev registry)")
			w("| name | tp | stand | cam | prompt |")
			w("|---|---|---|---|---|")
			local names = {}
			for k in st do
				table.insert(names, k)
			end
			table.sort(names)
			for _, k in names do
				local e = st[k]
				w(string.format(
					"| %s | %s | %s | %s | %s |",
					k,
					tostring(e.tp or ""),
					e.stand and "yes" or "auto",
					e.cam and "yes" or "auto",
					tostring(e.prompt or "")
				))
			end
			w("")
		end
	end

	w("## Workspace roots")
	for _, c in workspace:GetChildren() do
		if c:IsA("Model") or c:IsA("Folder") then
			local n = #Ref.prompts(c)
			local pos = c:IsA("Model") and v3(c:GetPivot().Position) or "-"
			w(string.format("- `%s` (%s) pivot %s, %d prompts", c.Name, c.ClassName, pos, n))
		end
	end
	w("")

	w("## ProximityPrompts")
	w("| path | action | object | hold | pos |")
	w("|---|---|---|---|---|")
	local ps = Ref.prompts(workspace)
	table.sort(ps, function(a, b)
		return Ref.path(a) < Ref.path(b)
	end)
	for i, p in ps do
		if opts.maxPrompts and i > opts.maxPrompts then
			w("| ... | | | | |")
			break
		end
		w(string.format(
			"| `%s` | %s | %s | %.2g | %s |",
			Ref.path(p),
			p.ActionText,
			p.ObjectText,
			p.HoldDuration,
			v3(Ref.worldPos(p))
		))
	end
	w("")

	w("## Remotes")
	local devRt = RS:FindFirstChild("SockDevRuntime")
	for _, d in RS:GetDescendants() do
		if d:IsA("RemoteEvent") or d:IsA("RemoteFunction") or d:IsA("UnreliableRemoteEvent") then
			if not (devRt and d:IsDescendantOf(devRt)) then
				w(string.format("- `%s` (%s)", d:GetFullName(), d.ClassName))
			end
		end
	end
	w("")

	local function listMods(title, root)
		if not root then
			return
		end
		w("## " .. title)
		for _, d in root:GetDescendants() do
			if d:IsA("LuaSourceContainer") then
				local ok, src = pcall(function()
					return d.Source
				end)
				local lines = ok and select(2, string.gsub(src, "\n", "\n")) + 1 or "?"
				w(string.format("- `%s` (%s, %s lines)", d:GetFullName(), d.ClassName, tostring(lines)))
			end
		end
		w("")
	end
	local SP = game:GetService("StarterPlayer")
	listMods("Client scripts", SP:FindFirstChild("StarterPlayerScripts") and SP.StarterPlayerScripts:FindFirstChild("SockClient"))
	listMods("Server scripts", game:GetService("ServerScriptService"):FindFirstChild("SockServer"))

	return table.concat(L, "\n")
end

-- ---------- source tools (Edit mode only) ----------

local function getSource(s)
	return s.Source
end

local function setSource(s, src)
	local ok = pcall(function()
		ses():UpdateSourceAsync(s, function()
			return src
		end)
	end)
	if not ok then
		s.Source = src
	end
end

-- Ref.grep("Teleport", "StarterPlayer") -> "path:line: text" lines (capped)
function Ref.grep(pattern, rootPath, max)
	local root = rootPath and Ref.find(rootPath) or game
	max = max or 60
	local out = {}
	local roots = root == game
			and {
				game:GetService("ServerScriptService"),
				game:GetService("StarterPlayer"),
				game:GetService("ReplicatedStorage"),
				game:GetService("StarterGui"),
				game:GetService("ServerStorage"),
				workspace,
			}
		or { root }
	for _, r in roots do
		local list = r:GetDescendants()
		if r:IsA("LuaSourceContainer") then
			table.insert(list, 1, r) -- a single script as root: search the script itself
		end
		for _, d in list do
			if d:IsA("LuaSourceContainer") then
				local ok, src = pcall(getSource, d)
				if ok then
					local n = 0
					for line in string.gmatch(src .. "\n", "(.-)\n") do
						n += 1
						if string.find(line, pattern) then
							table.insert(out, string.format("%s:%d: %s", d:GetFullName(), n, (string.gsub(line, "^%s+", ""))))
							if #out >= max then
								table.insert(out, "... (capped)")
								return table.concat(out, "\n")
							end
						end
					end
				end
			end
		end
	end
	return table.concat(out, "\n")
end

-- Ref.lines("ServerScriptService.SockServer.Main", 120, 160) -> numbered slice
function Ref.lines(path, from, to)
	local s = Ref.find(path)
	assert(s and s:IsA("LuaSourceContainer"), "no script at " .. tostring(path))
	local out, n = {}, 0
	from = from or 1
	to = to or (from + 80)
	for line in string.gmatch(getSource(s) .. "\n", "(.-)\n") do
		n += 1
		if n > to then
			break
		end
		if n >= from then
			table.insert(out, string.format("%4d  %s", n, line))
		end
	end
	return table.concat(out, "\n")
end

-- Exact-substring replace that must match exactly once. Avoids pasting whole sources.
-- Ref.patch(path, old, new)  or  Ref.patch(path, {{old, new}, {old2, new2}})
function Ref.patch(path, old, new)
	local s = Ref.find(path)
	assert(s and s:IsA("LuaSourceContainer"), "no script at " .. tostring(path))
	local edits = type(old) == "table" and old or { { old, new } }
	local src = getSource(s)
	for i, e in edits do
		local a, b = string.find(src, e[1], 1, true)
		assert(a, "edit " .. i .. ": old text not found")
		assert(not string.find(src, e[1], b + 1, true), "edit " .. i .. ": old text matches more than once")
		src = string.sub(src, 1, a - 1) .. e[2] .. string.sub(src, b + 1)
	end
	setSource(s, src)
	return string.format("patched %s (%d edit%s)", s:GetFullName(), #edits, #edits == 1 and "" or "s")
end

-- Replace a whole source. Creates the script if missing: class defaults to ModuleScript.
function Ref.push(path, src, class)
	local s = Ref.find(path)
	if not s then
		local parentPath, name = string.match(path, "^(.*)%.([^%.]+)$")
		local parent = parentPath and Ref.find(parentPath)
		assert(parent, "no parent for " .. path)
		s = Instance.new(class or "ModuleScript")
		s.Name = name
		s.Parent = parent
	end
	setSource(s, src)
	return "pushed " .. s:GetFullName() .. " (" .. #src .. " chars)"
end

-- Insert or replace one station line in ServerStorage.SockDev.Stations.
-- line is what D.record() prints, e.g. ["W2Gate"] = { tp = "W2Gate", stand = {...}, cam = {...} },
function Ref.upsertStation(line)
	local s = game:GetService("ServerStorage"):FindFirstChild("SockDev")
	s = s and s:FindFirstChild("Stations")
	assert(s, "ServerStorage.SockDev.Stations missing")
	local name = string.match(line, '^%s*%["([^"]+)"%]')
	assert(name, "line must start with [\"Name\"] =")
	local key = '["' .. name .. '"]'
	local out, done = {}, false
	for l in string.gmatch(getSource(s) .. "\n", "(.-)\n") do
		local trimmed = string.match(l, "^%s*(.-)$")
		if not done and string.sub(trimmed, 1, #key) == key then
			table.insert(out, "\t" .. (string.gsub(line, "^%s+", "")))
			done = true
		elseif not done and string.find(l, "@stations-end", 1, true) then
			table.insert(out, "\t" .. (string.gsub(line, "^%s+", "")))
			table.insert(out, l)
			done = true
		else
			table.insert(out, l)
		end
	end
	assert(done, "@stations-end marker missing")
	if out[#out] == "" then
		table.remove(out)
	end
	setSource(s, table.concat(out, "\n"))
	return "station " .. name .. " saved"
end

return Ref
