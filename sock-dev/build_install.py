#!/usr/bin/env python3
"""Bundles src/*.lua into install.lua: one execute_luau paste in Studio Edit mode."""
import pathlib, re
root = pathlib.Path(__file__).parent
src = root / "src"
items = [  # (key, parent, class, name, keep_if_exists)
    ("Ref", "SockDev", "ModuleScript", "Ref", False),
    ("Stations", "SockDev", "ModuleScript", "Stations", True),  # keep recorded viewpoints
    ("Client", "SockDev", "ModuleScript", "Client", False),
    ("Loader", "SockDev", "LocalScript", "Loader", False),
    ("Boot", "SSS", "Script", "SockDevBoot", False),
]
files = {"Ref": "Ref.lua", "Stations": "Stations.lua", "Client": "Client.lua",
         "Loader": "Loader.client.lua", "Boot": "SockDevBoot.server.lua"}
def lb(text):
    n = 1
    while f"]{'=' * n}]" in text: n += 1
    return "=" * n
out = ["-- SockDev installer (generated by build_install.py; do not edit by hand).",
       "-- Run once with execute_luau in EDIT mode. Idempotent. Never saves or publishes.",
       "-- Keeps an existing Stations registry unless _G.SOCKDEV_FORCE_STATIONS = true.",
       'local RunService = game:GetService("RunService")',
       'assert(not RunService:IsRunning(), "SockDev install: stop the playtest first (Edit mode only)")',
       'local SES = game:GetService("ScriptEditorService")',
       'local SS = game:GetService("ServerStorage")',
       'local SSS = game:GetService("ServerScriptService")',
       "local SRC = {}"]
for k, f in files.items():
    t = (src / f).read_text()
    e = lb(t)
    out.append(f"SRC.{k} = [{e}[\n{t}]{e}]")
out += [
 'local folder = SS:FindFirstChild("SockDev")',
 'if not folder then folder = Instance.new("Folder"); folder.Name = "SockDev"; folder.Parent = SS end',
 'local parents = { SockDev = folder, SSS = SSS }',
 'local report = {}',
 'local function put(parentKey, class, name, key, keep)',
 '\tlocal parent = parents[parentKey]',
 '\tlocal s = parent:FindFirstChild(name)',
 '\tif s and not s:IsA(class) then s:Destroy(); s = nil end',
 '\tlocal created = s == nil',
 '\tif created then s = Instance.new(class); s.Name = name; s.Parent = parent end',
 '\tif keep and not created and not _G.SOCKDEV_FORCE_STATIONS then table.insert(report, name .. " kept"); return end',
 '\tif class == "LocalScript" then s.Enabled = false end -- template; Boot enables the copies',
 '\tlocal ok = pcall(function() SES:UpdateSourceAsync(s, function() return SRC[key] end) end)',
 '\tif not ok then s.Source = SRC[key] end',
 '\ttable.insert(report, name .. (created and " created" or " updated"))',
 'end',
]
for k, parent, cls, name, keep in items:
    out.append(f'put("{parent}", "{cls}", "{name}", "{k}", {str(keep).lower()})')
out.append('return "SockDev installed: " .. table.concat(report, ", ") .. ". Do NOT save the place unless the user asks."')
(root / "install.lua").write_text("\n".join(out) + "\n")
(root / "uninstall.lua").write_text("""-- Removes SockDev from the place (Edit mode). Never saves.
assert(not game:GetService("RunService"):IsRunning(), "stop the playtest first")
local n = 0
for _, i in { game.ServerStorage:FindFirstChild("SockDev") or false, game.ServerScriptService:FindFirstChild("SockDevBoot") or false } do
\tif i then i:Destroy(); n += 1 end
end
return "SockDev removed (" .. n .. " instances)"
""")
print("install.lua", (root / "install.lua").stat().st_size, "bytes")
